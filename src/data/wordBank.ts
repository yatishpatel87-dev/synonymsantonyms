/**
 * Generates exactly 20 randomized questions for the selected level and mode.
 */
export function generateQuestionSet(level: GameLevel, mode: 'synonym' | 'antonym' | 'battle'): Question[] {
  // Pool matching level, or supplement with other levels if needed
  let pool = WORD_BANK.filter((w) => w.level === level);
  if (pool.length < 20) {
    // If pool is slightly smaller, blend with adjacent levels
    const otherWords = WORD_BANK.filter((w) => w.level !== level);
    pool = [...pool, ...otherWords];
  }

  // Shuffle the word pool
  const shuffledWords = [...pool].sort(() => 0.5 - Math.random());
  // Pick 20 words
  const selectedWords = shuffledWords.slice(0, 20);

  return selectedWords.map((vocab, index) => {
    // Determine question type based on game mode:
    let type: 'synonym' | 'antonym';
    if (mode === 'synonym') {
      type = 'synonym';
    } else if (mode === 'antonym') {
      type = 'antonym';
    } else {
      // 'battle' mode: alternate or randomly balance
      type = index % 2 === 0 ? 'synonym' : 'antonym';
    }

    const correctAnswerList = type === 'synonym' ? vocab.synonyms : vocab.antonyms;
    const oppositeList = type === 'synonym' ? vocab.antonyms : vocab.synonyms;
    const correctAnswer = correctAnswerList[Math.floor(Math.random() * correctAnswerList.length)];

    // Build 3 distractors:
    // Distractor 1: an opposite (antonym for synonym question or vice versa) to test deep discrimination!
    const oppositeTrap = oppositeList[0];

    // Other distractors from word's distractors or from other words in bank
    const availableDistractors = [...vocab.distractors];
    // Fill until we have at least 2 more
    while (availableDistractors.length < 2) {
      const randomWord = WORD_BANK[Math.floor(Math.random() * WORD_BANK.length)];
      if (randomWord.word !== vocab.word && !availableDistractors.includes(randomWord.word)) {
        availableDistractors.push(randomWord.word);
      }
    }

    const optionsRaw = [
      correctAnswer,
      oppositeTrap,
      availableDistractors[0],
      availableDistractors[1] || availableDistractors[0] + 'ly',
    ];

    // Deduplicate and randomize order
    const uniqueOptions = Array.from(new Set(optionsRaw));
    while (uniqueOptions.length < 4) {
      const randomFiller = WORD_BANK[Math.floor(Math.random() * WORD_BANK.length)].word;
      if (!uniqueOptions.includes(randomFiller)) {
        uniqueOptions.push(randomFiller);
      }
    }

    const shuffledOptions = uniqueOptions.sort(() => 0.5 - Math.random());

    const explanation =
      type === 'synonym'
        ? `"${correctAnswer}" is a synonym of "${vocab.word}". (સમાનાર્થી: ${vocab.synonyms.join(', ')})`
        : `"${correctAnswer}" is an antonym of "${vocab.word}". (વિરોધી: ${vocab.antonyms.join(', ')})`;

    return {
      id: `q-${index + 1}-${vocab.id}`,
      type,
      targetWord: vocab.word,
      gujaratiMeaning: vocab.gujaratiMeaning,
      partOfSpeech: vocab.partOfSpeech,
      exampleSentence: vocab.exampleSentence,
      options: shuffledOptions,
      correctAnswer,
      explanation,
      allSynonyms: vocab.synonyms,
      allAntonyms: vocab.antonyms,
    };
  });
}

